// Regenerates src/styles/theme-palette.css:  node scripts/generate-theme-palette.js > src/styles/theme-palette.css
// Light = Tailwind's stock colours (so existing classes render exactly as before).
// Dark  = a hand-tuned navy-tinted neutral scale for `slate`, and a mirrored scale
//         (step N takes light step 1000-N, with 500 -> light 400) for the status hues.
const colors = require('tailwindcss/colors');

const STATUS_FAMILIES = ['emerald', 'amber', 'red', 'sky', 'violet', 'rose', 'blue'];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');
const hslToRgb = (h, s, l) => {
  s /= 100;
  l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((x) => Math.round(x * 255)).join(' ');
};

// Roles, not a mirror: 50-300 are surfaces/borders/tracks (just above the dark
// card), 400-950 are text and all clear WCAG AA (>= 4.5:1) on the dark
// background, the card and slate-100.
const DARK_SLATE = {
  50: [215, 30, 13],
  100: [215, 28, 17],
  200: [215, 25, 22],
  300: [215, 22, 32],
  400: [215, 20, 62],
  500: [215, 20, 68],
  600: [215, 20, 74],
  700: [215, 25, 82],
  800: [215, 30, 90],
  900: [210, 40, 96],
  950: [210, 40, 98],
};

const mirroredStep = (step) => (step === 500 ? 400 : 1000 - step);

let light = '';
let dark = '';
for (const step of STEPS) {
  light += `  --slate-${step}: ${rgb(colors.slate[step])};\n`;
  dark += `  --slate-${step}: ${hslToRgb(...DARK_SLATE[step])};\n`;
}
for (const family of STATUS_FAMILIES) {
  for (const step of STEPS) {
    light += `  --${family}-${step}: ${rgb(colors[family][step])};\n`;
    dark += `  --${family}-${step}: ${rgb(colors[family][mirroredStep(step)])};\n`;
  }
}

process.stdout.write(`/* GENERATED by scripts/generate-theme-palette.js — edit the script, not this file.

   Convention: \`slate\`, \`emerald\`, \`amber\`, \`red\`, \`sky\`, \`violet\`, \`rose\` and \`blue\` are
   theme-aware (tailwind.config.ts maps every step to these variables). Light mode holds
   Tailwind's stock values, so existing classes render exactly as before. In dark mode:
   - slate: steps 50-300 become dark surfaces/borders, 400-950 light text greys;
   - status hues are MIRRORED (step N takes the value of step 1000-N, 500 takes 400):
     \`bg-emerald-50 text-emerald-700\` becomes a dark-green pill with light-green text.
   Write classes for the LIGHT theme and the dark one follows; reach for \`dark:\` only when
   a step does not read well. Channels are "R G B" so alpha modifiers (bg-slate-50/50) work. */

:root {
${light}}

.dark {
${dark}}
`);
